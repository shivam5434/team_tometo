"""Regenerate src/cities.py: curated list + every Indian city with population >= 100,000.

Run from phase2/:  pip install geonamescache && python tools/build_cities.py
City data: GeoNames (https://www.geonames.org), CC BY 4.0 -- credit it in the footer.

Rules
  * all curated cities are kept (state capitals, towns you care about)
  * GeoNames cities (pop >= MIN_POP) are added, largest first, unless an existing
    point is within MIN_SPACING_KM (the model is ~45 km, so closer points add nothing)
  * tiers (1 = shown zoomed out, 2 = from zoom 6, 3 = from zoom 7) are spaced so markers don't pile up
"""
import math
import sys
import unicodedata
from pathlib import Path

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE.parent / "src"))
sys.path.insert(0, str(HERE))

import geonamescache                                   # noqa: E402
from curated_cities import _RAW                        # noqa: E402
from grid import cell_id, in_india_bbox                # noqa: E402

MIN_POP, MIN_SPACING_KM = 100_000, 25.0
# GeoNames "population" is district-level for a few small places; skip ones I spotted.
BLOCKLIST = {"Kallakurichi", "Nowrangapur", "Punasa"}
CAPITALS = {"Delhi", "Mumbai", "Kolkata", "Chennai", "Bengaluru", "Hyderabad", "Jaipur", "Lucknow",
            "Bhopal", "Patna", "Ranchi", "Bhubaneswar", "Guwahati", "Chandigarh", "Dehradun", "Shimla",
            "Srinagar", "Jammu", "Leh", "Raipur", "Thiruvananthapuram", "Panaji", "Gangtok", "Itanagar",
            "Kohima", "Imphal", "Aizawl", "Shillong", "Agartala", "Port Blair", "Puducherry",
            "Kavaratti", "Vijayawada", "Ahmedabad", "Pune"}


def km(a, b):
    p1, p2 = math.radians(a[0]), math.radians(b[0])
    dp, dl = p2 - p1, math.radians(b[1] - a[1])
    h = math.sin(dp / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
    return 12742 * math.asin(math.sqrt(h))


gn = [c for c in geonamescache.GeonamesCache().get_cities().values()
      if c["countrycode"] == "IN" and c["population"] >= MIN_POP]
gn.sort(key=lambda c: -c["population"])


def own_pop(lat, lon):
    """Population of the GeoNames city within 15 km (so a small town next to a metro isn't promoted)."""
    near = [c for c in gn if km((lat, lon), (c["latitude"], c["longitude"])) <= 15]
    return max((c["population"] for c in near), default=0)


def plain(name):
    return unicodedata.normalize("NFKD", name).encode("ascii", "ignore").decode() or name


rows = []          # (name, lat, lon, pop)
taken = set()
for name, lat, lon in _RAW:
    rows.append((name, lat, lon, own_pop(lat, lon)))
    taken.add(cell_id(lat, lon))
for c in gn:
    lat, lon = round(c["latitude"], 2), round(c["longitude"], 2)
    if not in_india_bbox(lat, lon) or cell_id(lat, lon) in taken:
        continue
    if plain(c["name"]) in BLOCKLIST or plain(c["name"]) in {r[0] for r in rows}:
        continue            # blocked, or same name as a city we already have
    if any(km((lat, lon), (r[1], r[2])) < MIN_SPACING_KM for r in rows):
        continue
    rows.append((plain(c["name"]), lat, lon, c["population"]))
    taken.add(cell_id(lat, lon))

# Tiers decide when a marker appears while zooming in. Spacing keeps the map readable:
# tier 1 (zoomed out) >= 150 km apart, tier 2 >= 75 km from tiers 1-2, tier 3 = everything else.
# GeoNames populations for a few small towns are district-level, so only the hand-curated
# cities (and capitals) can reach tiers 1-2; GeoNames additions are tier 3.
curated_names = {n for n, _, _ in _RAW}
by_importance = sorted(rows, key=lambda r: (r[0] not in CAPITALS, -r[3]))
t1, t2 = [], []
for r in by_importance:
    if r[0] in CAPITALS or (r[0] in curated_names and r[3] >= 1_000_000):
        if all(km((r[1], r[2]), (q[1], q[2])) >= 150 for q in t1):
            t1.append(r)
t1_names = {r[0] for r in t1}
for r in sorted(rows, key=lambda r: -r[3]):
    if r[0] in t1_names or r[0] not in curated_names:
        continue
    if (r[3] >= 300_000 or r[0] in CAPITALS) and all(km((r[1], r[2]), (q[1], q[2])) >= 75 for q in t1 + t2):
        t2.append(r)
t2_names = {r[0] for r in t2}


def tier(name, pop):
    return 1 if name in t1_names else 2 if name in t2_names else 3


out = sorted(((n, la, lo, tier(n, p), p) for n, la, lo, p in rows), key=lambda r: (r[3], -r[4], r[0]))
lines = [f'    ({n!r}, {la}, {lo}, {t}),' for n, la, lo, t, _ in out]
Path(HERE.parent / "src" / "cities.py").write_text(f'''"""Generated by tools/build_cities.py -- do not edit by hand.

(name, lat, lon, tier). City list: curated + GeoNames (CC BY 4.0, geonames.org), pop >= {MIN_POP:,}.
tier 1 = capitals and 1M+ cities, 2 = 300k+, 3 = the rest.
"""
from grid import dedupe_by_cell

_ROWS = [
{chr(10).join(lines)}
]

CITIES = [{{"name": n, "lat": la, "lon": lo, "tier": t}} for n, la, lo, t in _ROWS]
POINTS = dedupe_by_cell(CITIES)   # one entry per 0.1-degree grid cell, with "cell" id
''')
from collections import Counter
print("points:", len(out), "| curated kept:", len(_RAW), "| tiers:", dict(sorted(Counter(r[3] for r in out).items())))
